create table if not exists public.predictions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  sku text not null,
  name text not null,
  days_to_depletion integer not null,
  stockout_risk text not null,
  reorder_recommended boolean not null default false,
  forecast_next_7_days numeric not null default 0,
  source text not null default 'manual',
  created_at timestamptz not null default timezone('utc', now())
);

alter table public.predictions enable row level security;

drop policy if exists "Users can read their predictions" on public.predictions;
create policy "Users can read their predictions"
  on public.predictions for select
  using (auth.uid() = user_id);

drop policy if exists "Users can create their predictions" on public.predictions;
create policy "Users can create their predictions"
  on public.predictions for insert
  with check (auth.uid() = user_id);

create index if not exists predictions_user_created_at_idx
  on public.predictions (user_id, created_at desc);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  po_reference text not null,
  sku text not null,
  medicine text not null,
  quantity integer not null check (quantity > 0),
  days_to_depletion integer not null,
  status text not null default 'Review' check (status in ('Review', 'Approved', 'Received', 'Cancelled')),
  created_at timestamptz not null default timezone('utc', now())
);

alter table public.orders enable row level security;

drop policy if exists "Users can read their orders" on public.orders;
create policy "Users can read their orders"
  on public.orders for select
  using (auth.uid() = user_id);

drop policy if exists "Users can create their orders" on public.orders;
create policy "Users can create their orders"
  on public.orders for insert
  with check (auth.uid() = user_id);

drop policy if exists "Users can update their orders" on public.orders;
create policy "Users can update their orders"
  on public.orders for update
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "Users can delete their orders" on public.orders;
create policy "Users can delete their orders"
  on public.orders for delete
  using (auth.uid() = user_id);

create index if not exists orders_user_created_at_idx
  on public.orders (user_id, created_at desc);

-- Keep the newest active order when upgrading an existing database.
delete from public.orders older
using public.orders newer
where older.user_id = newer.user_id
  and older.sku = newer.sku
  and older.status in ('Review', 'Approved')
  and newer.status in ('Review', 'Approved')
  and older.id < newer.id;

create unique index if not exists orders_one_active_sku_idx
  on public.orders (user_id, sku)
  where status in ('Review', 'Approved');